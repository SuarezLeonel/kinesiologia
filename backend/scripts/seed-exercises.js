export async function seedExercises(options = { verbose: true }) {
  const connection = await connectAdmin();
  try {
    const [existingRows] = await connection.query('SELECT id, name, is_active FROM exercises');
    const existingMap = new Map(existingRows.map(r => [r.name.trim().toLowerCase(), r]));

    const existingCount = existingRows.length;
    let createdCount = 0;
    let skippedCount = 0;

    for (const ex of clinicalExercisesCatalog) {
      const normalizedName = ex.name.trim().toLowerCase();
      if (existingMap.has(normalizedName)) {
        // Actualizar datos clínicos para garantizar contenido homologado sin pisar IDs
        const existingId = existingMap.get(normalizedName).id;
        await connection.query(
          `UPDATE exercises SET 
            category = ?, description = ?, instructions = ?, default_sets = ?, default_repetitions = ?,
            body_zone = ?, muscle_group = ?, therapeutic_objective = ?, equipment_needed = ?,
            difficulty_level = ?, contraindications = ?, is_active = 1
          WHERE id = ?`,
          [
            ex.category, ex.description, ex.instructions, ex.default_sets, ex.default_repetitions,
            ex.body_zone, ex.muscle_group, ex.therapeutic_objective, ex.equipment_needed,
            ex.difficulty_level, ex.contraindications, existingId
          ]
        );
        skippedCount++;
        continue;
      }

      await connection.query(
        `INSERT INTO exercises (
          name, category, description, instructions, default_sets, default_repetitions,
          media_url, is_active, body_zone, muscle_group, therapeutic_objective,
          equipment_needed, difficulty_level, contraindications
        ) VALUES (?, ?, ?, ?, ?, ?, NULL, 1, ?, ?, ?, ?, ?, ?)`,
        [
          ex.name,
          ex.category,
          ex.description,
          ex.instructions,
          ex.default_sets,
          ex.default_repetitions,
          ex.body_zone,
          ex.muscle_group,
          ex.therapeutic_objective,
          ex.equipment_needed,
          ex.difficulty_level,
          ex.contraindications
        ]
      );
      createdCount++;
    }

    const [totalActiveRows] = await connection.query('SELECT COUNT(*) as total FROM exercises WHERE is_active = 1');
    const totalActive = totalActiveRows[0]?.total || 0;

    if (options.verbose) {
      console.log('--- REPORTE DE CARGA DE CATÁLOGO CLÍNICO DE EJERCICIOS ---');
      console.log(`> Ejercicios que ya existían previamente: ${existingCount}`);
      console.log(`> Ejercicios nuevos creados e insertados: ${createdCount}`);
      console.log(`> Ejercicios existentes actualizados por idempotencia: ${skippedCount}`);
      console.log(`> Total de ejercicios activos en el catálogo: ${totalActive}`);
      console.log(`> Pendientes de revisión clínica profesional: ${clinicalExercisesCatalog.length} (Catálogo de referencia demostrativo que requiere evaluación individualizada por el kinesiólogo antes de su prescripción).`);
      console.log('----------------------------------------------------------');
    }

    return {
      existingCount,
      createdCount,
      skippedCount,
      totalActive,
      pendingClinicalReview: clinicalExercisesCatalog.length
    };
  } finally {
    await connection.end();
  }
}

if (process.argv[1] && process.argv[1].endsWith('seed-exercises.js')) {
  seedExercises()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error('Error al sembrar catálogo de ejercicios:', err);
      process.exit(1);
    });
}
